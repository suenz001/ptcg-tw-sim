// ⭐v6.571 起：對戰紀錄用詞分批統一（站長 2026-10-15）。拿「本版」與「舊版（BASE）」的 log 逐字比對的零回歸守衛，
//   比對前先把兩邊都正規化成新用詞（單一來源，IRON_RULES Rule 38）——守的是「行為（張數、順序、哪一行出現）不變」，
//   用詞改寫本身由 test-v6571 等用詞守衛負責。⚠ 只收已確定的固定改寫，不做模糊比對。
const FAINT = [
  [/被中毒傷害擊倒！/g, '因中毒傷害昏厥！'],
  [/被灼傷傷害擊倒！/g, '因灼傷傷害昏厥！'],
  [/系統擊倒檢查/g, '系統昏厥檢查'],
  [/被昏厥！/g, '昏厥！'],
  [/也被擊倒/g, '也昏厥'],
  [/有寶可夢被擊倒/g, '有寶可夢昏厥'],
  [/被擊倒([！，])/g, '昏厥$1'],
  [/ 被 (\S+?) KO，/g, ' 因 $1 的招式昏厥，'],
];
/** v6.571「擊倒／KO → 昏厥」的固定改寫（新字樣原樣不動，可以重複套用）。 */
export function normalizeLogWording(msg) {
  let s = String(msg ?? '');
  for (const [re, to] of FAINT) s = s.replace(re, to);
  return s;
}
