/**
 * v6.342 M6a「30th CELEBRATION」招式實裝 —— 批次 2（16 招｜傷害計算類：條件加成 ＋ 乘算）
 *
 * ⚠⚠ 卡面文字逐字取自 `static/cards/M6a.json`（台灣官方中文，`attacks[].effect`），未經簡化。
 * ⚠⚠ 本批**全部改寫傷害**（卡面 `damage` 是 `80+` / `70×` 這種條件式），所以 16 招裡
 *    15 招用 `regPre`；唯一例外是「甲賀忍蛙ex｜隱密斬」（卡面 damage 為空、傷害全部
 *    發生在 picker 解掉之後 ⇒ 只有 `regPost`）。
 *
 * ⭐ 用 `regPre` 前已跑過同名印刷碰撞檢查（`__m6a/collide_w2.mjs` + `wave2-keys.json`）：
 *   16 鍵**全部 OK** —— 全卡庫同名同招只有一種傷害與一種效果文字，
 *   不會重演 v6.333「皮卡丘ex｜打雷 SVM 220 / M6a 200」那種硬寫傷害打錯印刷的事故。
 *
 * ⭐ Rule 38：本批**不在卡檔裡寫任何判準**。每一招都指向 `effects.ts` 的中央 helper；
 *   新加的 9 支 helper 全部放在 effects.ts 當中央出口，並同時把站上既有的同措辭卡
 *   （電蜘蛛｜麻麻羅網、超級大嘴娃ex｜貪心、超級赫拉克羅斯ex｜重裝角擊、
 *     鐵斑葉｜復仇刀鋒、普隆隆姆｜捲土重來）一起收斂過去（log 與傷害逐字相同）。
 *
 * ⚠ 能量計數一律走 host-aware 中央述詞（countEnergyTypeHostAware / energyProvidesType /
 *   getBasicEnergyType）—— 特殊能量提供的屬性與張數不是一對一，且基本能量卡的
 *   `pokemonType` 恒 null，直讀必錯。
 */

import { regPre, regPost } from '../_shared';
import {
  selfHasEnergyTypePre,            // 若身上附有【X】能量卡 → +N
  prizesTakenMultiplyPre,          // 自己已取獎賞張數 × N
  selfAttachedEnergyMultiplyPre,   // 自身附加的【X】能量數量 × N
  chooseOppPokemonDamageByCounters,// 對手 1 隻寶可夢受到「其身上指示物數 × N」
  selfNamedPokemonMultiplyPre,     // 自己場上同名（含 ex）寶可夢數量 × N
  defIsExPre,                      // 對手戰鬥寶可夢為【ex】→ +N
  selfCountersMultiplyPre,         // 自身傷害指示物數量 × N
  defActiveEnergyMultiplyPre,      // 對手戰鬥寶可夢身上能量數量 × N
  selfBasicEnergyTypeCountPre,     // 自方全場基本能量的「屬性種類」數 × N
  selfDiscardEnergyMultiplyPre,    // 自己棄牌區能量卡張數 × N
  damageTakenLastOppTurnPlusPre,   // 上個對手回合這隻受到的招式傷害
  revengeDamageKOPre,              // 上個對手回合自己有寶可夢被招式傷害 KO → +N
  selfHandMultiplyPre,             // 自己手牌張數 × N
  selfHasToolPre,                  // 若身上附有「寶可夢道具」卡 → +N
  selfBenchMaxHpMultiplyPre,       // 自己備戰中最大HP＝H 的寶可夢數 × N
} from '../../effects';

// ══════════════════════════════════════════════════════════════════════════════
// ① 「若這隻寶可夢身上附有【X】能量卡，則增加 80 點傷害。」（2 招）
//    ⚠ 判定走 host-aware：古舊／稜鏡等「視為該屬性」的特殊能量同樣算數（v5.683）。
// ══════════════════════════════════════════════════════════════════════════════
// 008/103 萊希拉姆｜鐳射火焰 [Fire,C,C] 80+：若這隻寶可夢身上附有【雷】能量卡，則增加80點傷害。
regPre('萊希拉姆|鐳射火焰', selfHasEnergyTypePre(80, 80, 'Lightning', '鐳射火焰'));
// 050/103 捷克羅姆｜爆烈閃電 [L,C,C] 80+：若這隻寶可夢身上附有【火】能量卡，則增加80點傷害。
regPre('捷克羅姆|爆烈閃電', selfHasEnergyTypePre(80, 80, 'Fire', '爆烈閃電'));

// ══════════════════════════════════════════════════════════════════════════════
// ② 獎賞卡乘算（1 招）
// ══════════════════════════════════════════════════════════════════════════════
// 009/103 呆火鱷ex｜心情好火焰 [Fire,Fire,C] 70×：造成自己已經獲得的獎賞卡的張數×70點傷害。
//   ⚠ 卡面是「70×」不是「70+」⇒ 基礎 0，已取 0 張時傷害就是 0。
regPre('呆火鱷ex|心情好火焰', prizesTakenMultiplyPre(70, '心情好火焰'));

// ══════════════════════════════════════════════════════════════════════════════
// ③ 能量數量乘算（2 招）
//    ⚠ 「能量的數量」＝能量**單位數（個）**，不是張數（v5.676 裁定）：
//      火箭隊能量＝2 個、燃火能量附在進化體＝3 個、新衝天能量 on Stage2＝2 個。
// ══════════════════════════════════════════════════════════════════════════════
// 013/103 蓋歐卡｜水炮 [C,C,C,C] 60+：增加這隻寶可夢身上附加的【水】能量的數量×30點傷害。
regPre('蓋歐卡|水炮', selfAttachedEnergyMultiplyPre(60, 30, 'Water', '水炮'));
// 056/103 夢幻｜精神強念 [P,P] 10+：增加對手的戰鬥寶可夢身上附加的能量的數量×40點傷害。
//   ⚠ 主詞是「對手的**戰鬥**寶可夢」（不是全場）⇒ defActiveEnergyMultiplyPre，
//     不可用 oppAllEnergyMultiplyPre（那是「對手的所有寶可夢」型）。
//   ⚠ 全站另有 代歐奇希斯｜精神強念（80+，×20）等同名招式，key 不同、數字不同，別抄錯。
regPre('夢幻|精神強念', defActiveEnergyMultiplyPre(10, 40, 'all', '精神強念'));

// ══════════════════════════════════════════════════════════════════════════════
// ④ 依目標而定的狙擊（1 招）
// ══════════════════════════════════════════════════════════════════════════════
// 015/103 甲賀忍蛙ex｜隱密斬 [Water] dmg=''：
//   對手的1隻寶可夢受到那隻寶可夢身上放置的傷害指示物的數量×30點傷害。[在備戰區不計算弱點・抵抗力。]
//   ⚠ 卡面 damage 為空 ⇒ 戰鬥場沒有主線傷害，**不登記 regPre**（登了會憑空多打）。
//   ⚠ 主詞是「1隻**寶可夢**」（含戰鬥場）⇒ opp-poke-choose。
//   ⚠ 傷害依**選定目標**而定 ⇒ 走 snipe-variable 的 params.perCounter（v6.342 擴充）。
regPost('甲賀忍蛙ex|隱密斬', (state, aIdx) => chooseOppPokemonDamageByCounters(state, aIdx, 30, '隱密斬'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑤ 場上寶可夢計數（2 招）
// ══════════════════════════════════════════════════════════════════════════════
// 028/103 皮卡丘｜皮卡連鎖 [L,L,L] 40×：造成自己的場上的「皮卡丘（包含『寶可夢【ex】』）」的數量×40點傷害。
//   ⚠ 「場上」含戰鬥場＋備戰；出招的這隻自己也算 1 隻。
//   ⚠ 括號只多收「皮卡丘ex」；「皮卡丘&捷克羅姆GX」卡名不同，卡面沒寫 ⇒ 不算。
regPre('皮卡丘|皮卡連鎖', selfNamedPokemonMultiplyPre(0, 40, '皮卡丘', '皮卡連鎖'));
// 096/103 寶寶丁｜軟彈陣 [無費用] 30×：造成自己的最大HP為「30」的備戰寶可夢的數量×30點傷害。
//   ⚠ 主詞是「**備戰**寶可夢」⇒ 不含戰鬥場的自己（自己也是 HP30 的寶寶丁）。
//   ⭐⭐ v6.362 站長裁定 A-3：「如果改變hp，就以當下hp來算，因此如果當最大HP不是30hp，
//     則不列入計算(例如場上有激動競技場)」⇒ 中央述詞 getEffectiveHP，不是印刷 card.hp。
//   ⚠ 「最大HP」是**上限**（受傷不會變），不是剩餘 HP ⇒ 不可以拿 hp - damage 去比。
regPre('寶寶丁|軟彈陣', selfBenchMaxHpMultiplyPre(30, 0, 30, '軟彈陣'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑥ 對手是【ex】就加傷（1 招）
// ══════════════════════════════════════════════════════════════════════════════
// 043/103 皮卡丘｜鬥志雷霆 [L,C,C] 20+：若對手的戰鬥寶可夢為「寶可夢【ex】」，則增加80點傷害。
//   ⚠ 全站另有 雷伊布｜鬥志雷霆（90+90），招名相同但卡名不同 ⇒ key 不撞，別抄錯數字。
regPre('皮卡丘|鬥志雷霆', defIsExPre(20, 80, '鬥志雷霆'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑦ 自身傷害指示物乘算（1 招）
// ══════════════════════════════════════════════════════════════════════════════
// 046/103 皮卡丘｜氣沖沖伏特 [L] 10+：增加這隻寶可夢身上放置的傷害指示物的數量×10點傷害。
regPre('皮卡丘|氣沖沖伏特', selfCountersMultiplyPre(10, 10, '氣沖沖伏特'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑧ 基本能量「屬性種類」計數（1 招）
// ══════════════════════════════════════════════════════════════════════════════
// 059/103 仙子伊布ex｜鮮豔和聲 [P,C,C] 50×：造成自己的所有寶可夢身上附加的基本能量的屬性種類的數量×50點傷害。
//   ⚠ 數的是**屬性種類**（3 張基本【超】只算 1 種），不是張數也不是單位數。
//   ⚠ 現役基本能量卡 pokemonType 恒 null ⇒ 中央 getBasicEnergyType（由卡名推）；
//     特殊能量在它那裡回 null ⇒ 「基本能量」自動被濾掉，符合卡面。
regPre('仙子伊布ex|鮮豔和聲', selfBasicEnergyTypeCountPre(0, 50, '鮮豔和聲'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑨ 棄牌區／手牌張數乘算（2 招）
// ══════════════════════════════════════════════════════════════════════════════
// 066/103 露奈雅拉｜午夜之光 [P] 20+：增加自己的棄牌區的能量卡的張數×20點傷害。
//   ⚠ 卡面是「**張數**」⇒ 逐張計數（棄牌區裡火箭隊能量就只是 1 張，沒有單位加成）。
//   ⚠ 「能量卡」沒限定基本 ⇒ 特殊能量也算。
regPre('露奈雅拉|午夜之光', selfDiscardEnergyMultiplyPre(20, 20, '午夜之光'));
// 080/103 伽勒爾 喵喵｜寶物猛攻 [Metal] 10×：造成自己的手牌的張數×10點傷害。
regPre('伽勒爾 喵喵|寶物猛攻', selfHandMultiplyPre(0, 10, '寶物猛攻'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑩ 「上個對手的回合」狀態（2 招）
//    ⚠⚠ 兩者讀的都是**站上既有**的記錄機制，本批沒有新增任何 GameState 欄位（Rule 38）。
// ══════════════════════════════════════════════════════════════════════════════
// 071/103 鬃岩狼人｜雙倍奉還 [F] 10+：增加與在上個對手的回合這隻寶可夢受到的招式的傷害相同數值的傷害。
//   ⚠ 與 超級赫拉克羅斯ex｜重裝角擊 逐字同措辭 ⇒ 共用 damageTakenLastOppTurn（v6.256 唯一寫入點）。
regPre('鬃岩狼人|雙倍奉還', damageTakenLastOppTurnPlusPre(10, '雙倍奉還'));
// 077/103 月亮伊布｜報仇 [D] 30+：在上個對手的回合，若自己的寶可夢因招式的傷害而【昏厥】了，則增加100點傷害。
//   ⚠ 卡面寫「因招式的**傷害**而昏厥」⇒ 讀 oppDamageKOdMeInLastOppTurn（只計傷害 KO），
//     **不是** oppAttackKOdMeInLastOppTurn（那個含效果昏厥，給措辭不同的卡用）。
regPre('月亮伊布|報仇', revengeDamageKOPre(30, 100, '報仇'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑪ 道具條件加成（1 招）
// ══════════════════════════════════════════════════════════════════════════════
// 085/103 蒼響｜堅硬利刃 [Metal] 20+：若這隻寶可夢身上附有「寶可夢道具」卡，則增加40點傷害。
//   ⚠ 走 getAllAttachedTools —— 洛托姆ex｜多重轉接的第 2 張道具在 extraTools，只看 toolAttached 會漏。
regPre('蒼響|堅硬利刃', selfHasToolPre(20, 40, '堅硬利刃'));
