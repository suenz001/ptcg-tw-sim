/**
 * M6「綠寶石風暴」— 招式實裝 批次 3（v6.062）：8 招
 *
 * 選件判準同前兩批：**卡面措辭與既有 H/I/J 標卡逐字相同**（本批各型既有已實裝範本 19–72 張），
 * 全部復用中央 helper。本批另把 `rechargePost` 從 v2400 卡檔逐字搬到中央並 export。
 *
 * ⚠ 其中一張（煤炭龜｜烈焰爆）原本規劃在批次 1，寫檔時漏掉、本批補上（批次 1 的 changelog
 *   並未宣稱做過它，所以先前沒有錯誤說明）。
 */

import { regPre, regPost, updatePlayer, addLog } from '../_shared';
import {
  drawNPost, millOppDeckTopPost, skipDefEffectsPre,
  selfHealPost, selfSwapPost, rechargePost, flipCoinsWithLog,
} from '../../effects';

// ══════════════════════════════════════════════════════════════════════════════
// 1 抽牌（既有 72 張，範本：拉魯拉絲｜呼喚 drawNPost(1)）
//   赫拉克羅斯｜扣殺抽出 damage='20'：從自己的牌庫抽出2張卡。
// ══════════════════════════════════════════════════════════════════════════════
regPost('赫拉克羅斯|扣殺抽出', drawNPost(2, '扣殺抽出'));

// ══════════════════════════════════════════════════════════════════════════════
// 2 恢復自身 HP（既有 65 張，範本：橡實果｜小憩 selfHealPost(20)）
//   巨翅飛魚｜泡沫吸取 damage='30'：將這隻寶可夢恢復「30」HP。
// ══════════════════════════════════════════════════════════════════════════════
regPost('巨翅飛魚|泡沫吸取', selfHealPost(30, '泡沫吸取'));

// ══════════════════════════════════════════════════════════════════════════════
// 3 單招 recharge（既有 59 張，中央 rechargePost）
//   煤炭龜｜烈焰爆 damage='120'：在下個自己的回合，這隻寶可夢無法使用「烈焰爆」。
//   ⚠ 只鎖「烈焰爆」這一招（blockedAttackNamesNextTurn），其他招式照常可用。
// ══════════════════════════════════════════════════════════════════════════════
regPost('煤炭龜|烈焰爆', rechargePost('烈焰爆'));

// ══════════════════════════════════════════════════════════════════════════════
// 4 傷害不計對手身上的附加效果（既有 30 張，中央 skipDefEffectsPre）
//   雷電雲｜雷電刀鋒 damage='90'：這個招式的傷害不計算對手的戰鬥寶可夢身上的附加效果。
//   ⚠ 這類招式會 bypass 防禦方的減傷／免疫附加效果（既有中央 helper 已處理）。
// ══════════════════════════════════════════════════════════════════════════════
regPre('雷電雲|雷電刀鋒', skipDefEffectsPre(90, '雷電刀鋒'));

// ══════════════════════════════════════════════════════════════════════════════
// 5 傷害不計抵抗力（既有 19 張，範本：鹽石壘｜岩石投擲）
//   大鋼蛇｜重重橫掃 damage='150'：這個招式的傷害不計算抵抗力。
//   ⚠ 這是少數**必須**在 regPre 帶印刷傷害的型別 —— skipResistance 旗標只能隨 regPre 回傳；
//     數值 150 逐字對照 M6.json 的 attacks[].damage。
// ══════════════════════════════════════════════════════════════════════════════
regPre('大鋼蛇|重重橫掃', (s) => ({ state: s, damage: 150, skipResistance: true }));

// ══════════════════════════════════════════════════════════════════════════════
// 6 丟棄對手牌庫頂 N 張（既有 26 張，中央 millOppDeckTopPost）
//   穿山王｜挖洞爪 damage='60'：將對手的牌庫上方1張卡丟棄。
// ══════════════════════════════════════════════════════════════════════════════
regPost('穿山王|挖洞爪', millOppDeckTopPost(1, '挖洞爪'));

// ══════════════════════════════════════════════════════════════════════════════
// 7 自身與備戰互換（既有 22 張，中央 selfSwapPost；換下時走 clearActiveEffects 清狀態）
//   青綿鳥｜雀躍 damage=''：將這隻寶可夢與備戰寶可夢互換。
// ══════════════════════════════════════════════════════════════════════════════
regPost('青綿鳥|雀躍', selfSwapPost('雀躍'));

// ══════════════════════════════════════════════════════════════════════════════
// 8 擲幣正面 → 下個對手回合完全免疫（既有 28 張，範本：雪吞蟲｜躲藏／音波龍｜高速移動）
//   電海燕｜高速移動 damage='10'：擲1次硬幣若為正面，則在下個對手的回合，
//     這隻寶可夢不會受到招式的傷害與效果的影響。
//   ⚠ 卡面是「傷害**與效果**」→ 用 immuneToAllAttackNextTurn（完全免疫），
//     不可用 damageReduceNextHit:9999（那只擋傷害、擋不住效果）。
//     三張既有同措辭卡（雪吞蟲｜躲藏、音波龍｜高速移動、赫普的小木靈｜躍起閃避）皆用此欄位。
// ══════════════════════════════════════════════════════════════════════════════
regPost('電海燕|高速移動', (state, aIdx, _pool) => {
  const r = flipCoinsWithLog(state, 1, '高速移動', aIdx);
  if (r.heads !== 1) return r.state;
  return updatePlayer(
    addLog(r.state, '高速移動：正面 → 下個對手回合不受招式的傷害與效果影響', aIdx),
    aIdx, (p) => ({ ...p, active: p.active ? { ...p.active, immuneToAllAttackNextTurn: true } : null }),
  );
});
