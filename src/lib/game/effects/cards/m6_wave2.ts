/**
 * M6「綠寶石風暴」— 招式實裝 批次 2（v6.061）：12 招
 *
 * 與批次 1 相同判準：**卡面措辭與既有 H/I/J 標卡逐字相同**（各型既有範本 3–78 張），
 * 全部復用中央 helper，不新增機制、不簡化卡面。
 * 本批為此把 8 個 helper 收斂到中央 effects.ts 並 export（5 個原本就在 effects.ts 只是 local；
 * 3 個逐字從卡檔搬入），避免再產生第 3 份重複定義。
 *
 * ⚠ 條件加傷型（regPre）**必須**回傳 base / base+bonus 兩種值，這是既有做法；
 *   與「固定傷害禁硬編」不衝突——後者指的是無條件的純印刷傷害招式。
 *   每一條的 base 都逐字對照 static/cards/M6.json 的 attacks[].damage。
 */

import { regPre, regPost, addLog } from '../_shared';
import {
  defIsEvolvedPre, defIsExPre, coinPlusPre, oppBenchMultiplyPre,
  coinHeadsMultiplyPre, coinTailsFailPre, prizesConditionPre,
  chooseOppPokemonDamage, chooseOppBenchDamage,
} from '../../effects';

// ══════════════════════════════════════════════════════════════════════════════
// A 對手戰鬥寶可夢為進化寶可夢 → 加傷（既有 14 張，範本：毒骷蛙／肯泰羅｜俐落一擊）
//   蜂女王｜俐落一擊 damage='80+'：若對手的戰鬥寶可夢為進化寶可夢，則增加80點傷害。
// ══════════════════════════════════════════════════════════════════════════════
regPre('蜂女王|俐落一擊', defIsEvolvedPre(80, 80, '俐落一擊'));

// ══════════════════════════════════════════════════════════════════════════════
// B 對手身上有傷害指示物 → 加傷（既有 14 張，範本：布魯皇｜致命刺擊）
//   超級具甲武者ex｜致命刺擊 damage='60+'：…則增加160點傷害。
//   判準：對手 active.damage > 0（damage 即傷害指示物×10）。
// ══════════════════════════════════════════════════════════════════════════════
regPre('超級具甲武者ex|致命刺擊', (state, aIdx, _pool) => {
  const def = state.players[(1 - aIdx) as 0 | 1];
  const hurt = (def.active?.damage ?? 0) > 0;
  const dmg = hurt ? 60 + 160 : 60;
  return { state: addLog(state, `致命刺擊：對手${hurt ? '身上有傷害指示物 +160' : '身上無傷害指示物'} = ${dmg}`, aIdx), damage: dmg };
});

// ══════════════════════════════════════════════════════════════════════════════
// C 對手剩餘獎賞卡 ≤ N → 加傷（既有 7 張，範本：蒼響｜界限破壞）
//   風速狗｜活力獠牙 damage='90+'：若對手剩餘獎賞卡的張數為【4】張以下，則增加90點傷害。
//   ⚠ 門檻是 4，不是範本蒼響的 3 —— 逐字對照 M6.json，別照抄範本參數。
// ══════════════════════════════════════════════════════════════════════════════
regPre('風速狗|活力獠牙', prizesConditionPre(90, 90, 'opp', 'lte', 4, 'remaining', '活力獠牙'));

// ══════════════════════════════════════════════════════════════════════════════
// D 對手戰鬥寶可夢為「寶可夢【ex】」→ 加傷（既有 20 張，範本：火焰鳥｜鬥志之翼）
//   眷戀雲｜上升之心 damage='100+'：…則增加100點傷害。
// ══════════════════════════════════════════════════════════════════════════════
regPre('眷戀雲|上升之心', defIsExPre(100, 100, '上升之心'));

// ══════════════════════════════════════════════════════════════════════════════
// E 擲 1 次硬幣正面 → 加傷（既有 71 張，中央版 coinPlusPre）
//   刺球仙人掌｜擊飛 damage='10+'：擲1次硬幣若為正面，則增加10點傷害。
//   ⚠ 全站另有同招名的 普隆隆姆｜擊飛（90/90），key 不會撞，但別抄錯數字。
// ══════════════════════════════════════════════════════════════════════════════
regPre('刺球仙人掌|擊飛', coinPlusPre(10, 10, '擊飛'));

// ══════════════════════════════════════════════════════════════════════════════
// F 對手手牌張數 × N（取代式，既有 4 張，範本：超級雪妖女ex｜怨言）
//   引夢貘人｜意志統治者 damage='20×'：造成對手的手牌的張數×20點傷害。
// ══════════════════════════════════════════════════════════════════════════════
regPre('引夢貘人|意志統治者', (state, aIdx, _pool) => {
  const n = state.players[(1 - aIdx) as 0 | 1].hand.length;
  const dmg = n * 20;
  return { state: addLog(state, `意志統治者：對手手牌 ${n} 張 × 20 = ${dmg}`, aIdx), damage: dmg };
});

// ══════════════════════════════════════════════════════════════════════════════
// G 對手備戰數 × N（取代式，中央版 oppBenchMultiplyPre，既有 3 張）
//   超級烏賊王ex｜精神傀儡 damage='70×'：造成對手的備戰寶可夢的數量×70點傷害。
//   → base 0：對手 0 隻備戰時傷害為 0。
// ══════════════════════════════════════════════════════════════════════════════
regPre('超級烏賊王ex|精神傀儡', oppBenchMultiplyPre(0, 70, '精神傀儡'));

// ══════════════════════════════════════════════════════════════════════════════
// H 狙擊「對手的 1 隻寶可夢」（**含戰鬥位**）不計備戰弱抗（既有 43 張）
//   夢歌仙人掌｜直擊彈 damage=''：對手的1隻寶可夢受到30點傷害。[在備戰區不計算弱點・抵抗力。]
//   ⚠ 卡面主詞是「1隻寶可夢」（非「1隻備戰寶可夢」）→ 目標含戰鬥位，開 picker 讓玩家選；
//     chooseOppPokemonDamage 的 opp-poke-choose 在 UI 與 AI 兩端預設都含 active。
//     dealAttackDamageToTarget 已內建：選 active 計弱抗、選備戰不計，且走免疫 gate。
// ══════════════════════════════════════════════════════════════════════════════
regPre('夢歌仙人掌|直擊彈', (s) => ({ state: s, damage: 0 }));
regPost('夢歌仙人掌|直擊彈', (state, aIdx) => chooseOppPokemonDamage(state, aIdx, 30, '直擊彈'));

// ══════════════════════════════════════════════════════════════════════════════
// I 「對手的 1 隻【備戰】寶可夢也受到 N」（既有 48 張，範本：凱路迪歐｜穿通）
//   摩托蜥｜突圍 damage='110'：對手的1隻備戰寶可夢也受到30點傷害。[備戰不計弱抗]
//   ⚠ 「也」＝印刷 110 照常打戰鬥位（引擎讀卡資料），POST 再對備戰追加 30。
// ══════════════════════════════════════════════════════════════════════════════
regPost('摩托蜥|突圍', (state, aIdx) => chooseOppBenchDamage(state, aIdx, 30, '突圍'));

// ══════════════════════════════════════════════════════════════════════════════
// J 擲 N 次硬幣，正面次數 × 傷害（既有 78 張，中央版 coinHeadsMultiplyPre）
//   鱗甲龍｜雙重粉碎 damage='70×'：擲2次硬幣，造成正面出現的次數×70點傷害。
// ══════════════════════════════════════════════════════════════════════════════
regPre('鱗甲龍|雙重粉碎', coinHeadsMultiplyPre(2, 70, '雙重粉碎'));

// ══════════════════════════════════════════════════════════════════════════════
// K 擲 1 次硬幣反面 → 招式失敗（既有 30 張，中央版 coinTailsFailPre）
//   小箭雀｜偷襲 damage='30'：擲1次硬幣若為反面，則這個招式失敗。
// ══════════════════════════════════════════════════════════════════════════════
regPre('小箭雀|偷襲', coinTailsFailPre(30, '偷襲'));

// ══════════════════════════════════════════════════════════════════════════════
// L 本回合從指定卡進化 → 加傷（既有 5 張，範本：小霞的寶石海星｜乍然閃光）
//   大電海燕｜襲擊 damage='30+'：在這個回合，若這隻寶可夢從「電海燕」進化，則增加90點傷害。
//   ⚠ 判準只能看**實際進化來源** evolvedFromStack 末端；不可用 card.evolvesFrom
//     （那是卡面定義，恆等於「電海燕」→ 條件恆真，神奇糖果跳級時會誤加傷。
//      自爆磁怪｜衝天電光 原本就是這個 bug，本版一併修正）。
// ══════════════════════════════════════════════════════════════════════════════
regPre('大電海燕|襲擊', (state, aIdx, pool) => {
  const a = state.players[aIdx].active;
  if (!a) return { state, damage: 30 };
  const stack = a.evolvedFromStack ?? [];
  const lastEvoSource = stack.length > 0 ? pool.get(stack[stack.length - 1].cardId)?.name : null;
  const fromSwablu = a.evolvedThisTurn === true && lastEvoSource === '電海燕';
  const dmg = fromSwablu ? 30 + 90 : 30;
  return { state: addLog(state, `襲擊：${fromSwablu ? '本回合從電海燕進化 +90' : '本回合非從電海燕進化'} = ${dmg}`, aIdx), damage: dmg };
});
