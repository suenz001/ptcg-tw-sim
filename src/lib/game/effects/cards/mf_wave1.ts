import { regPre, regPost } from '../_shared';
import {
  revengeDamageKOPre,            // 「在上個對手的回合，若自己的寶可夢因招式的傷害而【昏厥】了，則增加 N 點傷害。」
  coinTailsFailPre,              // 「擲1次硬幣若為反面，則這個招式失敗。」
  coinHeadsSelfImmuneNextPost,   // 「擲1次硬幣若為正面，則在下個對手的回合，這隻寶可夢不會受到招式的傷害與效果的影響。」
  recruitBasicToBenchPost,       // 「從自己的牌庫選擇最多 N 張【基礎】寶可夢卡，放置於備戰區。並且重洗牌庫。」
  drawNPost,                     // 「從自己的牌庫抽出 N 張卡。」
  chooseOppBenchDamage,          // 「對手的1隻備戰寶可夢也受到 N 點傷害。[在備戰區不計算弱點・抵抗力。]」
  chooseOppPokemonDamage,        // 「對手的1隻寶可夢受到 N 點傷害。[在備戰區不計算弱點・抵抗力。]」
  coinStatusPost,                // 「擲1次硬幣若為正面，則將對手的戰鬥寶可夢【X】。」
  selfHealPost,                  // 「將這隻寶可夢恢復「N」HP。」
  selfDiscardAllEnergyPost,      // 「將這隻寶可夢身上附加的能量卡全部丟棄」
} from '../../effects';
import { deckSearchAttachToAnyPost } from './v2750_h_wave2_full';

// ══════════════════════════════════════════════════════════════════════════════
// 1. 復仇加成（revengeDamageKOPre）— 1 招
//    熱帶龍｜捲土重來 `30+`：
//      「在上個對手的回合，若自己的寶可夢因招式的傷害而【昏厥】了，則增加90點傷害。」
//    ⇒ 與 普隆隆姆｜捲土重來（SV6，H，同為 30+90）**逐字相同**。
//    ⚠ 判準是「因**招式的傷害**而昏厥」＝ damage-only KO bucket（v5.927），
//      效果 KO（中毒／灼傷／放指示物）不算 —— helper 內已經是這一份判準。
// ══════════════════════════════════════════════════════════════════════════════
regPre('熱帶龍|捲土重來', revengeDamageKOPre(30, 90, '捲土重來'));

// ══════════════════════════════════════════════════════════════════════════════
// 2. 擲幣反面則招式失敗（coinTailsFailPre）— 1 招
//    六尾｜踹 `30`：「擲1次硬幣若為反面，則這個招式失敗。」
//    ⇒ 與 炎兔兒｜踹（M1L，I，同為 30）**逐字相同**（全站 19 招同措辭）。
// ══════════════════════════════════════════════════════════════════════════════
regPre('六尾|踹', coinTailsFailPre(30, '踹'));

// ══════════════════════════════════════════════════════════════════════════════
// 3. 擲幣正面則自身下回合完全免疫（coinHeadsSelfImmuneNextPost）— 1 招
//    櫻花寶｜躲藏（無傷害）：
//      「擲1次硬幣若為正面，則在下個對手的回合，這隻寶可夢不會受到招式的傷害與效果的影響。」
//    ⇒ 與 雪吞蟲｜躲藏（M1S，I）**逐字相同**（全站 20 招同措辭）。
//    ⚠ 卡面是「傷害**與效果**」⇒ helper 的預設 immuneKind='all'（immuneToAllAttackNextTurn），
//      不是只擋傷害的 'damage'（那是鐵壁／棉花之翼那一型，卡面沒有「與效果」三個字）。
// ══════════════════════════════════════════════════════════════════════════════
regPost('櫻花寶|躲藏', coinHeadsSelfImmuneNextPost('躲藏'));

// ══════════════════════════════════════════════════════════════════════════════
// 4. 牌庫挑基本能量、以任意方式附於自己的寶可夢（deckSearchAttachToAnyPost）— 1 招
//    櫻花兒｜能量之禮（無傷害）：
//      「從自己的牌庫選擇最多2張基本能量卡，以任意方式附於自己的寶可夢身上。並且重洗牌庫。」
//    ⇒ 與 黑魯加｜鼓勵（SVM，H）／七夕青鳥｜哼唱充能（SV7a，H）**逐字相同**。
//    ⚠「以任意方式」＝ 可分散附給不同寶可夢（非 singleTarget）；
//      「最多」＝ 帶條件的牌庫搜尋，可以選 0 張（v6.126 判準）。helper 內已是這一份。
// ══════════════════════════════════════════════════════════════════════════════
regPost('櫻花兒|能量之禮', deckSearchAttachToAnyPost(2, '能量之禮'));

// ══════════════════════════════════════════════════════════════════════════════
// 5. 牌庫挑【基礎】放備戰（recruitBasicToBenchPost）— 1 招（兩個印刷共用同一個 key）
//    比克提尼｜呼朋引伴（無傷害）：
//      「從自己的牌庫選擇最多2張【基礎】寶可夢卡，放置於備戰區。並且重洗牌庫。」
//    ⇒ 與 毒電嬰｜呼朋引伴（M2，I）**逐字相同**（全站 14 招同措辭）。
//    ⚠ MF 有兩張比克提尼（019/040 與 041/040）卡名與招式名都相同 ⇒ 同一個 effectKey，
//      註冊一次兩張都吃得到（reg key 是「卡名|招式名」）。
// ══════════════════════════════════════════════════════════════════════════════
regPost('比克提尼|呼朋引伴', recruitBasicToBenchPost(2, '呼朋引伴'));

// ══════════════════════════════════════════════════════════════════════════════
// 6. 抽 N 張（drawNPost）— 1 招（兩個印刷共用）
//    捷拉奧拉｜快速抽出 `20`：「從自己的牌庫抽出1張卡。」
//    ⇒ 與 拉魯拉絲｜呼喚（M2a，I）等 27 張**逐字相同**。
// ══════════════════════════════════════════════════════════════════════════════
regPost('捷拉奧拉|快速抽出', drawNPost(1, '快速抽出'));

// ══════════════════════════════════════════════════════════════════════════════
// 7. 備戰狙擊（chooseOppBenchDamage）— 1 招（兩個印刷共用）
//    捷拉奧拉｜電氣子彈 `50`：
//      「對手的1隻備戰寶可夢也受到20點傷害。[在備戰區不計算弱點・抵抗力。]」
//    ⇒ 與 凱路迪歐｜穿通（M4，J）等 5 張**逐字相同**。
//    ⚠ 主詞是「**備戰**寶可夢」⇒ 用 chooseOppBenchDamage（只列備戰），
//      不是 chooseOppPokemonDamage（含戰鬥場）。
// ══════════════════════════════════════════════════════════════════════════════
regPost('捷拉奧拉|電氣子彈', (state, aIdx) => chooseOppBenchDamage(state, aIdx, 20, '電氣子彈'));

// ══════════════════════════════════════════════════════════════════════════════
// 8. 擲幣狀態（coinStatusPost）— 1 招
//    瑪力露麗｜泰山壓頂 `90`：「擲1次硬幣若為正面，則將對手的戰鬥寶可夢【麻痺】。」
//    ⇒ 與 電擊魔獸｜泰山壓頂（M6，J）等 34 張**逐字相同**。
//    helper 內已含完整免疫鏈（憨憨臉／硬岩鬥能量／特殊能量 status_immune）。
// ══════════════════════════════════════════════════════════════════════════════
regPost('瑪力露麗|泰山壓頂', coinStatusPost('paralyzed'));

// ══════════════════════════════════════════════════════════════════════════════
// 9. 自我恢復（selfHealPost）— 1 招
//    克雷色利亞｜極光增輝 `30`：「將這隻寶可夢恢復「30」HP。」
//    ⇒ 與 巨蔓藤｜吸取（M1S，I）等 20 張**逐字相同**。
// ══════════════════════════════════════════════════════════════════════════════
regPost('克雷色利亞|極光增輝', selfHealPost(30, '極光增輝'));

// ══════════════════════════════════════════════════════════════════════════════
// 10. 丟光自身能量 ＋ 指定 1 隻狙擊（selfDiscardAllEnergyPost ＋ chooseOppPokemonDamage）— 1 招
//    小隕星｜流星射擊（無傷害）：
//      「將這隻寶可夢身上附加的能量全部丟棄，對手的1隻寶可夢受到120點傷害。
//        [在備戰區不計算弱點・抵抗力。]」
//    ⇒ 與 投羽梟｜羽毛射擊（M3，J，同型但 90 點）**同一條管線**。
//    ⚠ 卡面這裡寫「能量」而非「能量卡」——「全部丟棄」的情況下兩者結果相同
//      （張數與個數都是「全部」），不影響判準。
//    ⚠ 主詞是「對手的**1隻寶可夢**」（沒有限定備戰）⇒ chooseOppPokemonDamage（含戰鬥場）。
//    ⚠ 順序照卡面：**先丟光能量，再造成傷害**。
// ══════════════════════════════════════════════════════════════════════════════
regPost('小隕星|流星射擊', (state, aIdx, pool) => {
  const s = selfDiscardAllEnergyPost('流星射擊')(state, aIdx, pool);
  return chooseOppPokemonDamage(s, aIdx, 120, '流星射擊');
});
