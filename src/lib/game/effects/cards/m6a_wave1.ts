/**
 * v6.341 M6a「30th CELEBRATION」招式實裝 —— 批次 1（26 招）
 *
 * ⚠⚠ 卡面文字逐字取自 `static/cards/M6a.json`（台灣官方中文），未經簡化。
 * ⚠⚠ 本批**全部復用既有中央 helper**，不新增任何判準（Rule 38）。
 *
 * ⭐ 為什麼一定要實裝：引擎結算招式是 `const preFn = ATTACK_PRE.get(key); if (preFn) {…}`
 *   —— 沒有 handler 就直接套卡面傷害、效果整段跳過。代價型招式（自傷／鎖招／丟能量）
 *   沒實裝時卡會**比實體卡更強**，所以 M6a 在卡效果補完前一直被 `lockedSets` 鎖著
 *   （v6.340 起改由後台 `config/cardPolicy` 控制）。
 *
 * ⭐ 只登記 `regPost`、**不寫 `regPre`**：純效果類招式的傷害一律讓引擎讀卡面。
 *   v6.333 的前科是 `皮卡丘ex|打雷` 在表裡硬寫 220、M6a 的印刷卻是 200
 *   ⇒ 凡是純數字傷害都不要寫死（`scripts/test-fixed-damage-base.mjs` 在守）。
 *   本批需要改寫傷害的四招（偷襲／嬉鬧／三重粉碎／鐵尾）走既有的擲幣 helper，
 *   其 base 參數與卡面逐字相符，且已用 `__v6341/collide_check.mjs` 確認
 *   **全卡庫同名同招只有一種傷害**（26 鍵全部 OK）。
 */

import { regPost } from '../_shared';
import {
  statusPost, coinStatusPost, selfHealPost, selfHitPost, selfCantAttackNextPost,
  rechargePost, coinTailsFailPre, coinPlusPre, coinHeadsMultiplyPre,
  drawNPost, snipeOneOppBenchPost, chooseOppPokemonDamage, hitBenchAllForCard,
} from '../../effects';
import { regPre } from '../_shared';

// ══════════════════════════════════════════════════════════════════════════════
// ① 必中狀態（4 招）—— 卡面 pattern：「將對手的戰鬥寶可夢【XX】。」
//    statusPost 內含憨憨臉／薄霧能量／硬岩鬥等完整免疫鏈（v2.92 起）。
// ══════════════════════════════════════════════════════════════════════════════
// 001/103 蛋蛋｜催眠術 dmg=''：將對手的戰鬥寶可夢【睡眠】。
regPost('蛋蛋|催眠術', statusPost('asleep'));
// 005/103 彩粉蝶｜毒粉 60：將對手的戰鬥寶可夢【中毒】。
regPost('彩粉蝶|毒粉', statusPost('poisoned'));
// 009/103 呆火鱷ex｜灼熱 dmg=''：將對手的戰鬥寶可夢【灼傷】。
regPost('呆火鱷ex|灼熱', statusPost('burned'));
// 062/103 水晶燈火靈｜奇異燈火 130：將對手的戰鬥寶可夢【灼傷】與【混亂】。
//   ⚠ 雙狀態要各自走一次 statusPost —— 兩種狀態的免疫來源不同
//     （憨憨臉只免疫【混亂】），合併成一次會讓其中一道免疫失效。
//     比照 v2400 的「火箭隊的臭臭泥｜渾身臭臭」wrapper 模式。
regPost('水晶燈火靈|奇異燈火', (state, aIdx, pool) => {
  const s1 = statusPost('burned')(state, aIdx, pool);
  return statusPost('confused')(s1, aIdx, pool);
});

// ══════════════════════════════════════════════════════════════════════════════
// ② 擲幣狀態（2 招）—— 「擲1次硬幣若為正面，則將對手的戰鬥寶可夢【麻痺】。」
// ══════════════════════════════════════════════════════════════════════════════
// 011/103 拉普拉斯｜冰凍光束 80
regPost('拉普拉斯|冰凍光束', coinStatusPost('paralyzed'));
// 017/103 皮卡丘｜電擊 20
regPost('皮卡丘|電擊', coinStatusPost('paralyzed'));

// ══════════════════════════════════════════════════════════════════════════════
// ③ 自我恢復（2 招）
// ══════════════════════════════════════════════════════════════════════════════
// 002/103 阿羅拉 椰蛋樹｜超級吸取 150：將這隻寶可夢恢復「50」HP。
//   ⚠ 卡面是固定 50，不是「與造成的傷害相同」⇒ 走 selfHealPost 不是 selfHealByDealtPost。
regPost('阿羅拉 椰蛋樹|超級吸取', selfHealPost(50, '超級吸取'));
// 021/103 皮卡丘｜小憩 dmg=''：將這隻寶可夢恢復「30」HP。
regPost('皮卡丘|小憩', selfHealPost(30, '小憩'));

// ══════════════════════════════════════════════════════════════════════════════
// ④ 自傷（3 招）—— 「這隻寶可夢也受到 N 點傷害。」
//    ⚠ 這類是**代價型**招式：不實裝＝卡比實體卡強，優先度最高。
// ══════════════════════════════════════════════════════════════════════════════
// 018/103 皮卡丘｜伏特攻擊 80：這隻寶可夢也受到30點傷害。
regPost('皮卡丘|伏特攻擊', selfHitPost(30, '伏特攻擊'));
// 030/103 皮卡丘｜撞一下 40：這隻寶可夢也受到10點傷害。
regPost('皮卡丘|撞一下', selfHitPost(10, '撞一下'));
// 049/103 閃電鳥｜雷轟 210：這隻寶可夢也受到60點傷害。
regPost('閃電鳥|雷轟', selfHitPost(60, '雷轟'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑤ 鎖招（3 招）
//    ⚠ 「無法使用招式」＝鎖**全部**招式（selfCantAttackNextPost）；
//      「無法使用『某招』」＝只鎖那一招（rechargePost）。兩者是不同機制，別混用。
// ══════════════════════════════════════════════════════════════════════════════
// 051/103 顫弦蠑螈｜閃電伏特 150：在下個自己的回合，這隻寶可夢無法使用招式。
regPost('顫弦蠑螈|閃電伏特', selfCantAttackNextPost());
// 055/103 超夢ex｜超能之力 230：在下個自己的回合，這隻寶可夢無法使用招式。
regPost('超夢ex|超能之力', selfCantAttackNextPost());
// 085/103 蒼響｜猛擊在地 120：在下個自己的回合，這隻寶可夢無法使用「猛擊在地」。
regPost('蒼響|猛擊在地', rechargePost('猛擊在地'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑥ 擲幣改寫傷害（3 招；第 4 招「鐵尾」在 effects.ts 與同型招式並列，見那裡的註解）
// ══════════════════════════════════════════════════════════════════════════════
// 016/103 弱丁魚｜偷襲 30：擲1次硬幣若為反面，則這個招式失敗。
regPre('弱丁魚|偷襲', coinTailsFailPre(30, '偷襲'));
// 041/103 皮卡丘｜嬉鬧 10+：擲1次硬幣若為正面，則增加20點傷害。
regPre('皮卡丘|嬉鬧', coinPlusPre(10, 20, '嬉鬧'));
// 087/103 賽富豪｜三重粉碎 50×：擲3次硬幣，造成正面出現的次數×50點傷害。
regPre('賽富豪|三重粉碎', coinHeadsMultiplyPre(3, 50, '三重粉碎'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑦ 抽 1 張（4 招）—— 「從自己的牌庫抽出1張卡。」
//    ⚠ 三隻喵喵的招式同名（聚寶功）但**卡名不同**，key 各自獨立；
//      卡面傷害各是 10／10／30，全部交給引擎讀卡面（本區只登記 POST）。
// ══════════════════════════════════════════════════════════════════════════════
// 039/103 皮卡丘｜晚間散步 dmg=''
regPost('皮卡丘|晚間散步', drawNPost(1, '晚間散步'));
// 075/103 阿羅拉 喵喵｜聚寶功 10
regPost('阿羅拉 喵喵|聚寶功', drawNPost(1, '聚寶功'));
// 080/103 伽勒爾 喵喵｜聚寶功 10
regPost('伽勒爾 喵喵|聚寶功', drawNPost(1, '聚寶功'));
// 092/103 喵喵｜聚寶功 30
regPost('喵喵|聚寶功', drawNPost(1, '聚寶功'));

// ══════════════════════════════════════════════════════════════════════════════
// ⑧ 狙擊／全體（4 招）
//    ⚠ 卡面括號「[在備戰區不計算弱點・抵抗力。]」是規則層的既有行為，
//      helper 內已處理，不需要也不可以再加旗標。
// ══════════════════════════════════════════════════════════════════════════════
// 019/103 皮卡丘｜電光 20：對手的1隻備戰寶可夢也受到20點傷害。
regPost('皮卡丘|電光', snipeOneOppBenchPost(20, '電光'));
// 069/103 路卡利歐｜波導彈 100：對手的1隻備戰寶可夢也受到60點傷害。
regPost('路卡利歐|波導彈', snipeOneOppBenchPost(60, '波導彈'));
// 032/103 皮卡丘｜瞄準電光 dmg=''：對手的1隻寶可夢受到20點傷害。
//   ⚠ 卡面是「1隻**寶可夢**」（含戰鬥場）不是「備戰寶可夢」⇒ chooseOppPokemonDamage。
regPost('皮卡丘|瞄準電光', (state, aIdx) => chooseOppPokemonDamage(state, aIdx, 20, '瞄準電光'));
// 012/103 急凍鳥｜冰雹 dmg=''：對手的所有寶可夢各受到30點傷害。[在備戰區不計算弱點・抵抗力。]
//   ⚠⚠ 這是**傷害**，不是「放置傷害指示物」⇒ **不可以**用 applyDamageToAllOpp
//     （那一支是指示物型的中央出口，由克希｜痛楚記憶 才是它的用法）。
//     本批第一版就是用錯了，被 test-v6238 的全卡池行為掃描抓到：
//     「實際掉血卻不顯示預估」—— 指示物型本來就不報預估數字，傷害型則必須報。
//   ⭐ 正確寫法照既有同措辭的「雪絨蛾｜冰凍羽擊」（v5.168 重設計後的版本）：
//     戰鬥場那 30 點交給 **mainline ATTACK**（弱點／抵抗力／攻擊方道具全套加成都要算），
//     備戰的 30 點走中央 hitBenchAllForCard（卡面「在備戰區不計算弱點・抵抗力」＝ raw +30，
//     helper 內含球形盾牌／藏隱／太古防壁／花之帷幔／太晶等備戰保護與 KO・獎賞結算）。
regPre('急凍鳥|冰雹', (s) => ({ state: s, damage: 30 }));
regPost('急凍鳥|冰雹', (state, aIdx, pool) =>
  hitBenchAllForCard(state, aIdx, (1 - aIdx) as 0 | 1, 30, pool, '冰雹'));
