/**
 * MF「頂級牌組組合 「太陽伊布・月亮伊布」」— 招式實裝 批次 2（v6.388）
 *
 * 批次 1（mf_wave1.ts）收的是「卡面措辭與既有卡逐字相同、直接復用既有中央 helper」的 10 招。
 * 這一批是剩下的 6 招 —— 它們**需要新的中央 helper**，六支全部放在 `effects.ts` 當中央出口，
 * 並把站上同措辭的既有卡一起收斂過去（Rule 38：同一個判準只能有一份）。
 *
 * ⭐ 本檔**不寫任何判準**，只有「卡名|招式名 → 哪一支中央 helper」的對照。
 * ⭐ 只註冊需要的那一半：印刷傷害由引擎讀卡資料（engine.ts 的 `parseInt(attack.damage)`）。
 *
 * ⚠⚠ 為什麼一定要在同一版做完（不是留到下一版）：
 *   引擎對「沒有 handler 的招式」是**靜默略過效果、只結算卡面傷害**，
 *   `scripts/lib/deck-locked-sets.mjs` 的檔頭把這件事寫成站上不變量，
 *   `test-v6333` 有一條「**不在**不開放清單裡的 live H/I/J 卡，未實裝招式必須是 0」。
 *   ⇒ 要嘛整包做完，要嘛把卡包鎖起來不給組牌（後者需要站長裁定）。這一版選擇做完。
 *
 * 卡面文字全部逐字取自 static/cards/MF.json（台灣官方中文）。
 */

import { regPre, regPost } from '../_shared';
import {
  ownFieldCountMultiplyPre,      // 「造成自己的場上寶可夢的數量×N點傷害。」
  healOneOwnBenchPost,           // 「將自己的1隻備戰寶可夢恢復「N」HP。」
  defHasCountersBonusPre,        // 「若對手的戰鬥寶可夢身上放置有傷害指示物，則增加N點傷害。」
  coinHeadsDefCantRetreatPost,   // 「擲1次硬幣若為正面，則在下個對手的回合，受到這個招式的寶可夢無法撤退。」
  coinHeadsDiscardOppEnergyPost, // 「擲N次硬幣，選擇與正面出現的次數相同數量的…能量，將其丟棄。」
  selfCountersBonusPre,          // 「增加這隻寶可夢身上放置的傷害指示物的數量×N點傷害。」
} from '../../effects';

// ══════════════════════════════════════════════════════════════════════════════
// 1. 自己場上寶可夢數量 × N（ownFieldCountMultiplyPre）
//    太陽伊布ex｜陽光律動 `30×`：「造成自己的場上寶可夢的數量×30點傷害。」
//    ⚠ 站上既有的同措辭卡都是 **×20**（君主蛇｜皇家指令、霜奶仙｜甜點圓陣、
//      索羅亞克ex｜狂暴亂打、大宇怪｜宇宙律動）—— 倍率逐字照 MF.json，不得照抄範本參數。
//    ⚠ 兩個印刷（019/040 與 042/040）卡名與招式名相同 ⇒ 同一個 key，註冊一次兩張都吃得到。
// ══════════════════════════════════════════════════════════════════════════════
regPre('太陽伊布ex|陽光律動', ownFieldCountMultiplyPre(30, '陽光律動'));

// ══════════════════════════════════════════════════════════════════════════════
// 2. 選 1 隻自己備戰恢復 N HP（healOneOwnBenchPost）
//    花療環環｜平和芳香（無傷害）：「將自己的1隻備戰寶可夢恢復「80」HP。」
//    ⚠ 與既有的「HP**全部**恢復」（風妖精｜治癒棉絮／鳳王｜神聖之息）是**不同措辭**，
//      走不同的 resolver key（heal-bench-one-amount vs heal-full-bench-one）——
//      絕不可以把新措辭塞進舊 key（pendingSelection 存在對戰狀態裡，部署瞬間會給錯恢復量）。
// ══════════════════════════════════════════════════════════════════════════════
regPost('花療環環|平和芳香', healOneOwnBenchPost(80, '平和芳香'));

// ══════════════════════════════════════════════════════════════════════════════
// 3. 對手有傷害指示物則加傷（defHasCountersBonusPre）
//    月亮伊布ex｜月光利爪 `100+`：
//      「若對手的戰鬥寶可夢身上放置有傷害指示物，則增加140點傷害。」
//    ⚠ 判準是「對手 active 身上**現在有沒有**指示物」，不是「受過傷」——
//      被治療回滿的寶可夢身上沒有指示物，卡面就不該加傷。
//    ⚠ 兩個印刷（022/040 與 043/040）共用同一個 key。
// ══════════════════════════════════════════════════════════════════════════════
regPre('月亮伊布ex|月光利爪', defHasCountersBonusPre(100, 140, '月光利爪'));

// ══════════════════════════════════════════════════════════════════════════════
// 4. 擲幣正面 → 對手下回合無法撤退（coinHeadsDefCantRetreatPost）
//    黑暗鴉｜抓一下 `20`：
//      「擲1次硬幣若為正面，則在下個對手的回合，受到這個招式的寶可夢無法撤退。」
//    ⚠ 主詞是「**受到這個招式的**寶可夢」＝綁被打的那隻；
//      helper 內轉給 defCantRetreatNextPost，招式效果免疫 gate 在那一支裡。
//    ⚠ 卡池裡「在下個對手的回合，受到這個招式的寶可夢無法撤退」有 76 招，
//      但**帶擲幣條件**的只有這一張 ⇒ helper 是新開的，不是漏掉既有的。
// ══════════════════════════════════════════════════════════════════════════════
regPost('黑暗鴉|抓一下', coinHeadsDefCantRetreatPost('抓一下'));

// ══════════════════════════════════════════════════════════════════════════════
// 5. 擲 N 幣 → 丟棄對手戰鬥寶可夢的 N 個能量（coinHeadsDiscardOppEnergyPost）
//    三首惡龍｜三首啃咬（無傷害）：
//      「擲3次硬幣，選擇與正面出現的次數相同數量的對手的戰鬥寶可夢身上附加的能量，將其丟棄。」
//    ⚠ 卡面是「**選擇**…將其丟棄」⇒ 攻擊方有選擇權，走中央 discardOppActiveEnergyPost 的
//      picker（v5.800 的鐵律：選能量一律 picker，禁自動取末張）。
//    ⚠ 0 次正面 ⇒ 什麼都不丟；對手能量不足 N 個 ⇒ 只丟得到的那幾張（中央那一支已經是這個行為）。
// ══════════════════════════════════════════════════════════════════════════════
regPost('三首惡龍|三首啃咬', coinHeadsDiscardOppEnergyPost(3, '三首啃咬'));

// ══════════════════════════════════════════════════════════════════════════════
// 6. 自身傷害指示物數 × N（selfCountersBonusPre）
//    袋獸｜憤怒 `20+`：「增加這隻寶可夢身上放置的傷害指示物的數量×10點傷害。」
//    ⚠ 指示物數 = floor(damage / 10)，走既有的 counterCount，不得自己再除一次 10。
// ══════════════════════════════════════════════════════════════════════════════
regPre('袋獸|憤怒', selfCountersBonusPre(20, 10, '憤怒'));
