/**
 * M6「綠寶石風暴」— 招式實裝 批次 1（v6.060）
 *
 * 本批只收「卡面措辭與既有 H/I/J 標卡**逐字相同**」的招式，全部復用既有中央 helper，
 * 不新增任何機制、不簡化任何卡面。每一條都標註了措辭出現次數（含本批）作為類推依據。
 *
 * ⭐ 只註冊 POST：招式的**印刷傷害由引擎讀卡資料**（static/cards M6.json 的 attacks[].damage），
 *    不寫 `regPre(key, () => ({damage: N}))` 硬編數字 —— 硬編是舊檔的技術債，卡面才是權威。
 *
 * 卡面文字全部來自 static/cards/M6.json（台灣官方中文）。
 */

import { regPost } from '../_shared';
import {
  statusPost, coinStatusPost, defCantRetreatNextPost,
  defCantAttackNextPost, selfCantAttackNextPost, selfDmgReducePost,
} from '../../effects';

// ══════════════════════════════════════════════════════════════════════════════
// 1. 必中特殊狀態（statusPost）— 4 招
//    卡面：「將對手的戰鬥寶可夢【X】。」
//    statusPost 已含完整免疫鏈（憨憨臉／硬岩鬥能量／特殊能量 status_immune）。
// ══════════════════════════════════════════════════════════════════════════════
const M6_STATUS: Array<[string, 'poisoned' | 'burned' | 'asleep' | 'confused']> = [
  ['煤炭龜|灼燒', 'burned'],            // 將對手的戰鬥寶可夢【灼傷】。
  ['引夢貘人|催眠波動', 'asleep'],      // 將對手的戰鬥寶可夢【睡眠】。
  ['圓絲蛛|毒針', 'poisoned'],          // 將對手的戰鬥寶可夢【中毒】。
  ['超級烏賊王ex|不祥波動', 'confused'],// 將對手的戰鬥寶可夢【混亂】。
];
for (const [key, st] of M6_STATUS) regPost(key, statusPost(st));

// ══════════════════════════════════════════════════════════════════════════════
// 2. 擲幣狀態（coinStatusPost）— 1 招
//    卡面：「擲1次硬幣若為正面，則將對手的戰鬥寶可夢【麻痺】。」
// ══════════════════════════════════════════════════════════════════════════════
regPost('電擊魔獸|泰山壓頂', coinStatusPost('paralyzed'));

// ══════════════════════════════════════════════════════════════════════════════
// 3. 對手無法撤退（defCantRetreatNextPost）— 2 招
//    卡面：「在下個對手的回合，受到這個招式的寶可夢無法撤退。」（全站 76 招同措辭）
//    ⚠ 主詞是「受到這個招式的寶可夢」＝ 綁被打的那隻，helper 內已含招式效果免疫 gate。
// ══════════════════════════════════════════════════════════════════════════════
regPost('超級具甲武者ex|四爪控制', defCantRetreatNextPost('四爪控制'));
regPost('火箭雀|緊抓', defCantRetreatNextPost('緊抓'));

// ══════════════════════════════════════════════════════════════════════════════
// 4. 對手下回合無法使用招式（defCantAttackNextPost）— 1 招
//    卡面：「在下個對手的回合，受到這個招式的寶可夢無法使用招式。」（全站 12 招同措辭）
// ══════════════════════════════════════════════════════════════════════════════
regPost('雨翅蛾|恐怖花紋', defCantAttackNextPost());

// ══════════════════════════════════════════════════════════════════════════════
// 5. 自身下回合無法使用招式（selfCantAttackNextPost）— 1 招
//    卡面：「在下個自己的回合，這隻寶可夢無法使用招式。」＝**全部招式**（全站 111 招同措辭）
//    ⚠ 與「無法使用『某招名』」是不同機制（後者只擋該招，走 blockedAttackNamesNextTurn）。
//    ⚠ 雷公ex｜力量猛攻 雖同屬本型，但帶「擲1次硬幣若為反面」條件 → 不在本批，留待下批。
// ══════════════════════════════════════════════════════════════════════════════
regPost('尼多后|終極衝擊', selfCantAttackNextPost());

// ══════════════════════════════════════════════════════════════════════════════
// 6. 自身下次受招傷害 -30（selfDmgReducePost）— 2 招
//    卡面：「在下個對手的回合，這隻寶可夢受到招式的傷害「-30」點。」
//    與已實裝的 橡實果｜硬化 / 煤炭龜｜甲殼衝撞（皆 -30）**逐字相同** → 直接類推。
//    ⚠ 主詞是「這隻寶可夢受到…」＝ 自身防護，不是削弱對手攻擊（v5.997 主詞方向判準）。
// ══════════════════════════════════════════════════════════════════════════════
regPost('大岩蛇|防守壓制', selfDmgReducePost(30));
regPost('心鱗寶|硬頭', selfDmgReducePost(30));
