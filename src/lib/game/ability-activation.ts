// ⭐v6.489「這個特性能不能由玩家按按鈕發動」的唯一卡面判準（leaf 模組：不 import 任何引擎檔，避免成環）。
//
// 站長回報（2026-10-06）：狙射樹梟ex｜狙擊手之眼是被動特性（比照月月熊 赫月ex｜老練招式），
//   對戰畫面卻出現「使用特性」按鈕，按下去還寫出一行內部說明 log。
// 根因：早年為了「讓稽核表命中」替被動特性註冊了 noop regA，而 getUsableAbilities 只問
//   「有沒有註冊 regA」⇒ 只要註冊了就給按鈕。全站稽核找到 4 個同型（狙擊手之眼／光之翼／整人擊落／雙重屬性）。
//
// 判準（只看台灣官方卡面 abilities[].effect）：
//   ・玩家可以主動發動的特性，卡面一定寫「可使用」（含「可使用1次」「可不限次數使用」「可以使用」）。
//   ・被動特性（只要在場上就生效／條件成立自動生效／被丟棄時觸發）卡面沒有這個字樣。
//   全卡池（含 G 標）已註冊 regA 的 140 個特性逐一比對：不符合的恰好就是上述 4 個被動特性（test-v6489 釘住）。
//
// ⚠ 這只是「能不能給按鈕」的必要條件，不是充分條件 —— 觸發型（放置／進化／回備戰時可使用1次）
//   另有自己的集合與提示流程，getUsableAbilities 原本就會排除，不受這支影響。
// ⭐v6.494（Fable 審查 C）：「可使用」後面同一句（到「。」為止）講的是**招式**的被動特性
//   （潛入記憶／記憶螺旋「可使用…招式」、力量抑制者／啟動限制「才可使用招式」、出道演出、祭典樂舞）不是發動條件
//   ⇒ 以否定前瞻排除。全卡池比對：與舊判準只差這 9 個被動特性（test-v6489 A6～A14 釘住）。
const ACTIVATABLE_TEXT = /可(?:不限次數)?使用(?![^。]*招式)|可以使用(?![^。]*招式)/;

/** 卡面文字顯示這是「玩家可主動使用」的特性（被動特性回傳 false）。 */
export function isManuallyActivatableAbilityText(effect: string | null | undefined): boolean {
  // 卡庫曾出現零寬字元混在文字裡（v6.117），先剝掉再比對
  return typeof effect === 'string' && ACTIVATABLE_TEXT.test(effect.replace(/[\u200b-\u200d\ufeff]/g, ''));
}
