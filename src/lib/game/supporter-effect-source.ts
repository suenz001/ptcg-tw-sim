/**
 * ⭐⭐⭐ v6.262 —「這個支援者效果是**怎麼**發動的」單一來源。
 *
 * 背景（卡面逐字，全部讀 `static/cards` 台灣官方卡面）：
 *   站內四個「對支援者免疫」的來源，卡面**全部**逐字寫著「對手**從手牌使出**支援者卡時」：
 *     ・陳舊的鰭之化石｜鰭之守護（M3 18046，J）
 *         「對手從手牌使出支援者卡時，這隻寶可夢不會受到那個效果的影響。」
 *     ・斧牙龍｜緊張感（10627，H）／浩大鯨ex｜融合為雪（12782，I）
 *         「對手從手牌使出物品卡或者支援者卡時，這隻寶可夢不會受到那個效果的影響。」
 *     ・超甲狂犀｜廣域堡壘（10947，H）
 *         「只要這隻寶可夢在戰鬥場上，對手從手牌使出支援者卡時，
 *           自己的所有寶可夢不會受到那個效果的影響。」
 *
 * ⇒「從手牌使出」是**四個免疫的共同前提**，不是修飾語。站內另有兩張卡會把支援者的效果
 *   當成**招式的效果**執行，兩者都**不是**「從手牌使出支援者卡」：
 *     ・九尾｜靈怪變化（13968，I）「將自己的牌庫上方1張卡丟棄，若那張卡為支援者卡，
 *         則將那個效果作為這個招式的效果使用。」
 *     ・魔牆人偶｜相仿秀（9872，H）「查看對手的手牌。若希望，選擇1張其中的支援者卡，
 *         將那個效果作為這個招式的效果使用。」
 *   v6.261 以前這兩條路徑直接呼叫 `TRAINER_EFFECTS.get(name)(...)`，於是**連免疫也一起繼承**，
 *   化石被錯誤地排除在候選之外。依卡面逐字，這兩者不該免疫。
 *
 * ⚠ 設計上刻意做成「環境值 + 預設 from-hand」而不是逐一改 6 個消費點的簽章：
 *   消費點（候選過濾器）身處 resolver 深處，**根本拿不到「是誰在執行我」的資訊**；
 *   若改成必填參數，每個呼叫端都只能硬填 'from-hand'，等於沒有修。
 * ⚠⚠ **fail-closed**：預設值是 `'from-hand'`（＝免疫照舊生效）。任何新的執行路徑若忘了宣告，
 *   行為與 v6.261 完全相同（免疫），不會意外把免疫關掉造成公平性漏洞。
 *   只有明確用 `runAsCopiedSupporterEffect()` 包起來的那一段才會關閉免疫。
 *
 * ⚠ 本檔**零 import**（葉子模組）—— 免疫述詞、engine、卡檔都會讀它，
 *   有任何 import 就可能在循環依賴下觸發模組層級 const 的 TDZ（v6.078 教訓）。
 */

/** 支援者效果的發動來源。 */
export type SupporterEffectSource =
  /** 玩家從自己手牌使出這張支援者卡（＝四個免疫的卡面前提）。 */
  | 'from-hand'
  /** 支援者的效果被「作為招式的效果」複製執行（九尾｜靈怪變化、魔牆人偶｜相仿秀）。 */
  | 'copied-effect';

/** ⚠ fail-closed 預設值：沒人宣告過就是「從手牌使出」＝免疫照常生效。 */
let _current: SupporterEffectSource = 'from-hand';

/** 讀取目前正在執行的支援者效果來源。免疫述詞在沒有拿到明確參數時讀這裡。 */
export function getSupporterEffectSource(): SupporterEffectSource {
  return _current;
}

/**
 * 把 `fn` 當成「被招式複製的支援者效果」執行（期間 `getSupporterEffectSource()` 回
 * `'copied-effect'`）。
 *
 * ⚠ `finally` 還原成**呼叫前**的值而不是寫死 `'from-hand'`：將來若出現巢狀複製
 *   （複製到的支援者又複製別的）才不會提早把旗標關掉。
 */
export function runAsCopiedSupporterEffect<T>(fn: () => T): T {
  const prev = _current;
  _current = 'copied-effect';
  try {
    return fn();
  } finally {
    _current = prev;
  }
}
